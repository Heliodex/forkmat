// TestGeneratedFileIsNotRewritten checks that -strict reorders an ordinary file, and leaves a generated one as it is.
func TestGeneratedFileIsNotRewritten(t *testing.T) {
	const (
		body = "package p\n\nfunc f() {}\n\nvar a = 1\n"
		marker = "// Code generated by tool. DO NOT EDIT.\n\n"
	)

	tests := []struct {
		name, src string

		// wantVarFirst is whether the var is moved above the function
		wantVarFirst bool
	}{
		{
			name: "ordinary file",
			src: body,
			wantVarFirst: true,
		},
		{
			name: "generated file",
			src: marker + body,
			wantVarFirst: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			resetFlags()
			initParserMode()
			initRewrite()

			*strict = true

			t.Cleanup(func() {
				*strict = false
			})

			*write = true
			name := filepath.Join(t.TempDir(), "x.go")

			if err := os.WriteFile(name, []byte(tt.src), 0o644); err != nil {
				t.Fatal(err)
			}

			info, err := os.Lstat(name)
			if err != nil {
				t.Fatal(err)
			}

			var buf, errBuf bytes.Buffer

			s := newSequencer(2<<20, &buf, &errBuf)

			s.Add(fileWeight(name, info), func(r *reporter) error {
				return processFile(name, info, nil, r)
			})
			if s.GetExitCode() != 0 {
				t.Fatalf("exit code %d: %s", s.GetExitCode(), errBuf.String())
			}

			out, err := os.ReadFile(name)
			if err != nil {
				t.Fatal(err)
			}

			if varFirst := strings.Index(string(out), "var a") < strings.Index(string(out), "func f"); varFirst != tt.wantVarFirst {
				t.Errorf("var above func = %v, want %v:\n%s", varFirst, tt.wantVarFirst, out)
			}
		})
	}
}

func TestIsGenerated(t *testing.T) {
	tests := []struct {
		name, src string
		want bool
	}{
		{
			name: "Go convention",
			src: "// Code generated by tool. DO NOT EDIT.\n\npackage p\n",
			want: true,
		},
		{
			name: "wit-bindgen",
			src: "// Generated by `wit-bindgen` 0.61.1. DO NOT EDIT!\n//\n//     wasi:clocks@0.3.0\n\npackage p\n",
			want: true,
		},
		{
			name: "a marker after the package clause does not count",
			src: "package p\n\n// Code generated by tool. DO NOT EDIT.\n",
			want: false,
		},
		{
			name: "a mention in ordinary text does not count",
			src: "package p\n\n// The output says DO NOT EDIT. when generated.\n",
			want: false,
		},
		{
			name: "a program that writes the marker is not generated",
			src: "package p\n\nvar s = \"// Code generated from a table. DO NOT EDIT.\\n\"\n",
			want: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			file, err := parser.ParseFile(token.NewFileSet(), "x.go", tt.src, parser.ParseComments|parser.SkipObjectResolution)
			if err != nil {
				t.Fatalf("parse: %v", err)
			}

			if got := isGenerated(file); got != tt.want {
				t.Errorf("isGenerated = %v, want %v", got, tt.want)
			}
		})
	}
}
